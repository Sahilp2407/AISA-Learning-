// Convert email to formatted student record
export function parseStudentFromEmail(email, index) {
  const hash = hashString(email);
  const parts = email.split('@')[0].split('.');
  
  let batchYear = '2024';
  let rawHandle = email.split('@')[0].toLowerCase();

  if (parts.length > 1) {
    batchYear = parts[0];
    rawHandle = parts.slice(1).join('.').toLowerCase();
  } else {
    const match = email.match(/^(\d{4})/);
    if (match) {
      batchYear = match[1];
      rawHandle = email.split('@')[0].substring(4).toLowerCase();
    }
  }

  // Look up student name or fallback to capitalized clean name
  let nameClean = STUDENT_NAMES_MAP[rawHandle];
  if (!nameClean) {
    const cleanAlpha = rawHandle.replace(/[^a-zA-Z]/g, '');
    nameClean = cleanAlpha.charAt(0).toUpperCase() + cleanAlpha.slice(1);
  }
  // Strictly keep only the first name and remove last name
  nameClean = nameClean.trim().split(' ')[0];

  // Semester mapping based on batch
  let semester = 'Semester 2';
  let semNumber = 2;
  if (batchYear === '2023') {
    semester = 'Semester 4';
    semNumber = 4;
  } else if (batchYear === '2025') {
    semester = 'Semester 2';
    semNumber = 2;
  } else {
    semester = 'Semester 3';
    semNumber = 3;
  }

  // Course completion rate (65% to 98%)
  const completionRate = 65 + (hash % 34);

  // Test Average Score (70% to 98%)
  const avgTestScore = 70 + ((hash * 7) % 29);

  // Individual Test Breakdown
  const quiz1Score = Math.min(20, Math.floor(15 + ((hash % 6)))); // out of 20
  const midtermScore = Math.min(100, Math.floor(70 + ((hash * 3) % 28))); // out of 100
  const labScore = Math.min(50, Math.floor(40 + ((hash * 11) % 11))); // out of 50

  // Attendance
  const attendance = Math.min(100, Math.floor(84 + (hash % 16)));

  // AI Activity
  const aiQueriesCount = 15 + (hash % 95);
  const flaggedQueries = (hash % 19 === 0) ? 1 : 0;

  // Status Tag
  let performanceStatus = 'On Track';
  if (completionRate >= 85 && avgTestScore >= 85) {
    performanceStatus = 'Top Performer';
  } else if (completionRate < 75 || avgTestScore < 75) {
    performanceStatus = 'Needs Support';
  }

  return {
    id: `isu-std-${index + 1}`,
    rollNo: `ISU-${batchYear}-${(index + 101).toString().padStart(4, '0')}`,
    email,
    name: nameClean,
    batchYear,
    semester,
    semNumber,
    department: 'Computer Science & Engineering',
    completionRate,
    avgTestScore,
    quiz1Score,
    midtermScore,
    labScore,
    attendance,
    aiQueriesCount,
    flaggedQueries,
    performanceStatus,
    enrolledSubjects: semNumber === 2 ? [
      { code: 'CS201', name: 'Object Oriented Programming in C++', completion: Math.min(100, completionRate + 4), score: `${Math.round(avgTestScore * 0.95)}%` },
      { code: 'CS202', name: 'Digital Logic & Computer Design', completion: Math.max(50, completionRate - 5), score: `${Math.round(avgTestScore * 1.02)}%` },
      { code: 'CS204', name: 'DBMS - SQL & Relational Architecture', completion: completionRate, score: `${avgTestScore}%` },
      { code: 'MA201', name: 'Linear Algebra & Probability', completion: Math.min(100, completionRate + 2), score: `${Math.round(avgTestScore * 0.98)}%` },
    ] : [
      { code: 'CS301', name: 'Data Structures & Algorithms - II', completion: completionRate, score: `${avgTestScore}%` },
      { code: 'CS302', name: 'Operating Systems & Concurrency', completion: Math.max(55, completionRate - 4), score: `${Math.round(avgTestScore * 0.96)}%` },
      { code: 'CS303', name: 'Computer Networks & TCP/IP Architecture', completion: Math.min(100, completionRate + 6), score: `${Math.round(avgTestScore * 1.01)}%` }
    ]
  };
}

